"""Standard export formats: git patch, VPAT-style conformance report, Jira CSV, GitHub issues, JUnit XML.

All builders are pure functions over data AccessLoop already holds, so the same output comes from the web UI, the
Streamlit app and the command line.
"""
from __future__ import annotations
import csv
import difflib
import html as html_std
import io
from datetime import datetime, timezone
from xml.sax.saxutils import escape as xml_escape, quoteattr

from . import __version__

IMPACT_PRIORITY = {'critical': 'Highest', 'serious': 'High', 'moderate': 'Medium', 'minor': 'Low'}


# ---- patch -----------------------------------------------------------------------------------------------------
def git_patch(original: str, working: str, path: str = 'index.html', author: str = '', subject: str = '',
              new_files: dict | None = None) -> str:
    """A `git am`-compatible patch (and a plain unified diff underneath) from the original to the repaired page,
    including any new files the fixes created (for example captions), placed next to the page."""
    a = original.splitlines(keepends=True)
    b = working.splitlines(keepends=True)
    diff = ''.join(difflib.unified_diff(a, b, fromfile=f'a/{path}', tofile=f'b/{path}', n=3))
    if not diff:
        return ''
    if not diff.endswith('\n'):
        diff += '\n\\ No newline at end of file\n'
    folder = path.rsplit('/', 1)[0] + '/' if '/' in path else ''
    for name, text in sorted((new_files or {}).items()):
        lines = text.splitlines(keepends=True)
        diff += (f'diff --git a/{folder}{name} b/{folder}{name}\nnew file mode 100644\n--- /dev/null\n+++ b/{folder}{name}\n'
                 f'@@ -0,0 +1,{len(lines)} @@\n' + ''.join('+' + ln if ln.endswith('\n') else '+' + ln + '\n' for ln in lines))
    when = datetime.now(timezone.utc).strftime('%a, %d %b %Y %H:%M:%S +0000')
    who = author.strip() or 'AccessLoop reviewer'
    head = (f'From 0000000000000000000000000000000000000000 Mon Sep 17 00:00:00 2001\n'
            f'From: {who} <accessloop@localhost>\nDate: {when}\n'
            f'Subject: [PATCH] {subject or "Accessibility fixes approved and verified with AccessLoop"}\n\n'
            f'Generated by AccessLoop {__version__}. Every change was approved by a reviewer and re-verified by a\n'
            f'browser scan; see the evidence report and audit log for details.\n---\n'
            f'diff --git a/{path} b/{path}\n')
    return head + diff + '-- \nAccessLoop\n'


# ---- VPAT-style accessibility conformance report ----------------------------------------------------------------
def conformance(state: dict, catalog: dict, manual: dict | None = None) -> list[dict]:
    """One row per WCAG 2.2 A/AA criterion with a VPAT conformance term and remarks.

    Supports / Partially Supports / Does Not Support / Not Applicable / Not Evaluated, from: current automated results
    for the criterion's axe rules, plus the reviewer's manual-test results where recorded."""
    manual = manual or {}
    current = (state.get('rule_counts') or {}).get('current', {})
    reviews = {u['rule'] for u in state.get('unresolved', []) if u.get('kind') == 'review'}
    rows = []
    for c in catalog['criteria']:
        rules = c['axe_rules']
        failing = sorted(r for r in rules if current.get(r))
        unsure = sorted(r for r in rules if r in reviews)
        m = manual.get(c['criterion']) or {}
        result = m.get('result')
        if failing:
            level = 'Does Not Support' if result in (None, 'fail') else 'Partially Supports'
            remark = 'Automated checks still fail: ' + ', '.join(failing) + '.'
        elif result == 'fail':
            level, remark = 'Does Not Support', 'Failed the manual check.'
        elif result == 'partial':
            level, remark = 'Partially Supports', 'Manual check found some problems.'
        elif result == 'na':
            level, remark = 'Not Applicable', 'Reviewer recorded that the page has no content this criterion applies to.'
        elif result == 'pass':
            level = 'Supports'
            remark = 'Passed the manual check' + (' and the automated checks.' if rules else '.')
        elif rules and not unsure:
            level = 'Supports'
            remark = 'Automated checks pass; a manual check is still recommended.'
        elif unsure:
            level, remark = 'Not Evaluated', 'Automated results need review: ' + ', '.join(unsure) + '.'
        else:
            level, remark = 'Not Evaluated', 'Needs a manual check (no automated rule exists).'
        if m.get('notes'):
            remark += f' Reviewer note: {m["notes"]}'
        rows.append({'criterion': c['criterion'], 'name': c['name'], 'level': c['level'], 'conformance': level,
                     'remarks': remark})
    return rows


def acr_html(state: dict, catalog: dict, manual: dict | None = None, product: str = '') -> str:
    rows = conformance(state, catalog, manual)
    e = html_std.escape
    counts = {}
    for r in rows:
        counts[r['conformance']] = counts.get(r['conformance'], 0) + 1
    body = ''.join(f'<tr><td>{e(r["criterion"])} {e(r["name"])} (Level {e(r["level"])})</td><td>{e(r["conformance"])}</td>'
                   f'<td>{e(r["remarks"])}</td></tr>' for r in rows)
    summary = ' · '.join(f'{k}: {v}' for k, v in sorted(counts.items()))
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Accessibility Conformance Report</title>
<style>body{{font:15px/1.5 system-ui,sans-serif;max-width:1000px;margin:24px auto;padding:0 16px;color:#111}}
table{{border-collapse:collapse;width:100%}}th,td{{border:1px solid #bbb;padding:6px 8px;text-align:left;vertical-align:top}}
th{{background:#eef}}caption{{text-align:left;font-weight:600;margin:8px 0}}</style></head><body><main>
<h1>Accessibility Conformance Report (VPAT®-style, WCAG 2.2 edition)</h1>
<p><b>Product / page:</b> {e(product or state.get('source_name', ''))}<br><b>Report date:</b> {datetime.now(timezone.utc):%d %B %Y}<br>
<b>Evaluation method:</b> AccessLoop {e(__version__)}: axe-core {e((state.get('engine') or {}).get('axe', ''))} in headless
{e((state.get('engine') or {}).get('browser', 'Chromium'))}, plus the reviewer's manual checks recorded in AccessLoop.<br>
<b>Summary:</b> {e(summary)}</p>
<p>Terms follow the VPAT 2.5 definitions. "Supports" based on automated checks alone is provisional: automated tools find only
part of all barriers. This report is not a certification.</p>
<table><caption>Table 1: WCAG 2.2 Level A and AA success criteria</caption><thead><tr><th scope="col">Criteria</th>
<th scope="col">Conformance level</th><th scope="col">Remarks and explanations</th></tr></thead><tbody>{body}</tbody></table>
<p>VPAT® is a registered trademark of the Information Technology Industry Council (ITI). This is a VPAT-style report, not an
official ITI template.</p></main></body></html>"""


# ---- issue trackers -----------------------------------------------------------------------------------------------
def _issues(state: dict) -> list[dict]:
    out = []
    for u in state.get('unresolved', []):
        out.append({'rule': u['rule'], 'impact': u.get('impact') or 'moderate', 'selector': u['selector'], 'help': u['help'],
                    'wcag': u.get('wcag') or [], 'url': u.get('help_url', ''), 'kind': u.get('kind', 'violation'),
                    'handling': u.get('handling_label', ''), 'description': u.get('description', '')})
    return out


def jira_csv(state: dict) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(['Summary', 'Issue Type', 'Priority', 'Labels', 'Labels', 'Description'])
    page = state.get('source_name', 'page')
    for i in _issues(state):
        wcag = ', '.join(i['wcag']) or 'best practice'
        desc = (f'Page: {page}\nElement: {i["selector"]}\nRule: {i["rule"]} (WCAG {wcag})\n'
                f'{"Needs review: axe could not decide." if i["kind"] == "review" else ""}\n{i["description"]}\n'
                f'AccessLoop handling: {i["handling"]}\nGuidance: {i["url"]}')
        w.writerow([f'[a11y] {i["help"]} - {page}', 'Bug', IMPACT_PRIORITY.get(i['impact'], 'Medium'), 'accessibility',
                    f'wcag-{(i["wcag"] or ["bp"])[0]}', desc])
    return buf.getvalue()


def github_issues(state: dict) -> str:
    """Markdown with one issue per finding, plus a shell script block that files them with the GitHub CLI."""
    page = state.get('source_name', 'page')
    issues = _issues(state)
    md = [f'# Accessibility issues for {page}', '', f'{len(issues)} issue(s) that need a person. Generated by AccessLoop {__version__}.', '']
    script = ['#!/bin/sh', '# Files each issue with the GitHub CLI (gh). Review before running.', 'set -e']
    for n, i in enumerate(issues, 1):
        title = f'[a11y] {i["help"]} ({page})'.replace('"', "'")
        body = (f'**Element:** `{i["selector"]}`  \n**Rule:** `{i["rule"]}`, WCAG {", ".join(i["wcag"]) or "best practice"}, '
                f'impact {i["impact"]}  \n**Guidance:** {i["url"]}  \n**AccessLoop:** {i["handling"]}')
        md += [f'## {n}. {i["help"]}', '', body, '']
        script.append(f'gh issue create --label accessibility --title {quoteattr(title)} --body {quoteattr(body)}')
    return '\n'.join(md) + '\n\n```sh\n' + '\n'.join(script) + '\n```\n'


# ---- JUnit ---------------------------------------------------------------------------------------------------------
def junit_xml(results: list[dict]) -> str:
    """One <testsuite> per page and one <testcase> per rule found there; violations are failures. CI systems
    (GitHub Actions, Jenkins, GitLab) display these natively."""
    suites = []
    for r in results:
        page = r.get('file') or r.get('source_name') or 'page'
        if r.get('status', 'scanned') != 'scanned':
            suites.append(f'<testsuite name={quoteattr(page)} tests="1" failures="0" errors="1"><testcase name="load" '
                          f'classname={quoteattr(page)}><error message={quoteattr(r.get("error", ""))}/></testcase></testsuite>')
            continue
        by_rule: dict[str, list] = {}
        for f in r['findings']:
            by_rule.setdefault(f['rule'], []).append(f)
        cases, failures = [], 0
        for rule, items in sorted(by_rule.items()):
            viol = [f for f in items if f['kind'] == 'violation']
            if viol:
                failures += 1
                text = '\n'.join(f'line {f.get("line") or "?"}: {f["selector"]} ({f["impact"]})' for f in viol)
                cases.append(f'<testcase name={quoteattr(rule)} classname={quoteattr(page)}><failure '
                             f'message={quoteattr(viol[0]["help"])}>{xml_escape(text)}</failure></testcase>')
            else:
                cases.append(f'<testcase name={quoteattr(rule)} classname={quoteattr(page)}><skipped '
                             f'message="needs review"/></testcase>')
        if not cases:
            cases.append(f'<testcase name="no automated violations" classname={quoteattr(page)}/>')
        suites.append(f'<testsuite name={quoteattr(page)} tests="{len(cases)}" failures="{failures}" errors="0">'
                      + ''.join(cases) + '</testsuite>')
    return '<?xml version="1.0" encoding="UTF-8"?>\n<testsuites name="AccessLoop">' + ''.join(suites) + '</testsuites>\n'
